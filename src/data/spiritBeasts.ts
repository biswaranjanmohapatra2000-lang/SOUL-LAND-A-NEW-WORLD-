export function getBeastAgeCategory(years: number): BeastAgeCategory {
  if (years >= 900000) return BEAST_AGE_CATEGORIES.find(c => c.id === 'million_year')!;
  if (years >= 100000) return BEAST_AGE_CATEGORIES.find(c => c.id === 'hundred_thousand')!;
  if (years >= 10000) return BEAST_AGE_CATEGORIES.find(c => c.id === 'ten_thousand')!;
  if (years >= 1000) return BEAST_AGE_CATEGORIES.find(c => c.id === 'thousand_year')!;
  if (years >= 100) return BEAST_AGE_CATEGORIES.find(c => c.id === 'hundred_year')!;
  return BEAST_AGE_CATEGORIES.find(c => c.id === 'ten_year')!;
}

