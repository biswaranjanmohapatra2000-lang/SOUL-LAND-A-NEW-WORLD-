export function getBeastElement(beast: SpiritBeast): string {
  if (beast.element) return beast.element;
  const id = beast.id.toLowerCase();
  const name = beast.name.toLowerCase();
  const cn = beast.chineseName;

  if (id.includes('plant') || id.includes('bamboo') || id.includes('vine') || id.includes('ginseng') || id.includes('grass') || id.includes('ah_yin') || cn.includes('草') || cn.includes('竹') || cn.includes('藤') || cn.includes('参') || cn.includes('皇')) return 'wood';
  if (id.includes('fire') || id.includes('flame') || id.includes('phoenix') || id.includes('hell') || id.includes('sun') || cn.includes('火') || cn.includes('炎') || cn.includes('凤') || cn.includes('烈阳')) return 'fire';
  if (id.includes('ice') || id.includes('snow') || id.includes('water') || id.includes('frost') || id.includes('whale') || id.includes('silkworm') || cn.includes('冰') || cn.includes('雪') || cn.includes('水') || cn.includes('霜') || cn.includes('鲸') || cn.includes('蚕')) return 'water';
  if (id.includes('rhino') || id.includes('mammoth') || id.includes('porcupine') || id.includes('titan') || id.includes('bear') || cn.includes('犀') || cn.includes('象') || cn.includes('豪') || cn.includes('猿') || cn.includes('熊')) return 'earth';
  if (id.includes('thunder') || id.includes('lightning') || cn.includes('雷') || cn.includes('电')) return 'lightning';
  if (id.includes('dark') || id.includes('ghost') || id.includes('shadow') || id.includes('abyss') || id.includes('civet') || cn.includes('暗') || cn.includes('鬼') || cn.includes('幽冥') || cn.includes('影') || cn.includes('深渊')) return 'darkness';
  if (id.includes('light') || id.includes('holy') || id.includes('angel') || id.includes('swan') || id.includes('white') || id.includes('rabbit') || id.includes('butterfly') || cn.includes('光') || cn.includes('圣') || cn.includes('鹅') || cn.includes('兔') || cn.includes('蝶')) return 'light';
  if (id.includes('spider') || id.includes('snake') || id.includes('serpent') || id.includes('demon') || id.includes('poison') || cn.includes('蛛') || cn.includes('蛇') || cn.includes('毒') || cn.includes('魔')) return 'evil';
  if (id.includes('dragon') || cn.includes('龙')) return 'dragon';
  return 'earth';
}

